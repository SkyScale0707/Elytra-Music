package com.ggscaletest.client.mixin;

import net.minecraft.client.MinecraftClient;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.Inject;
import org.spongepowered.asm.mixin.injection.callback.CallbackInfo;

import com.ggscaletest.ElytraMusic;

@Mixin(MinecraftClient.class)
public class ExampleClientMixin {
	@Inject(at = @At("HEAD"), method = "run")
	private void init(CallbackInfo info) {
		// This code is injected into the start of MinecraftClient.run()V
		ElytraMusic.LOGGER.info("ElytraMusicTrackerMixin loaded successfully!");
		System.out.println("ElytraMusicTrackerMixin loaded successfully!\nby cmd");
	}
}